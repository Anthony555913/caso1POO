public class BattleField{
    private int X;
    private int Y;

    public BattleField() {
    }

    public BattleField(int pX, int pY) {
        this.X = pX;
        this.Y = pY;
    }

    public int getX() {
        return X;
    }

    public void setX(int pX) {
        this.X = pX;
    }

    public int getY() {
        return Y;
    }

    public void setY(int pY) {
        this.Y = pY;
    }

}